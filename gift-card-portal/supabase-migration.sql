create or replace function public.sync_customer_from_order()
returns trigger language plpgsql security definer set search_path = public
as $$
begin
  insert into public.customers(name, phone, division, district, upazila, address, order_count, lifetime_value, last_order_at)
  values (new.customer_name, new.customer_phone, new.division, new.district, new.upazila, new.address, 1, coalesce(new.total,0), coalesce(new.created_at,now()))
  on conflict (phone) do update set
    name = excluded.name,
    division = excluded.division,
    district = excluded.district,
    upazila = excluded.upazila,
    address = excluded.address,
    order_count = public.customers.order_count + 1,
    lifetime_value = public.customers.lifetime_value + excluded.lifetime_value,
    last_order_at = excluded.last_order_at,
    updated_at = now();
  return new;
end $$;

drop trigger if exists trg_sync_customer_from_order on public.orders;
create trigger trg_sync_customer_from_order
after insert on public.orders
for each row execute function public.sync_customer_from_order();

-- Backfill customer profiles from existing orders (safe to rerun without double-counting).
insert into public.customers(name, phone, division, district, upazila, address, order_count, lifetime_value, last_order_at)
select customer_name, customer_phone,
       (array_agg(division order by created_at desc))[1],
       (array_agg(district order by created_at desc))[1],
       (array_agg(upazila order by created_at desc))[1],
       (array_agg(address order by created_at desc))[1],
       count(*)::integer, coalesce(sum(total),0), max(created_at)
from public.orders
group by customer_phone
on conflict (phone) do update set
  name=excluded.name, division=excluded.division, district=excluded.district,
  upazila=excluded.upazila, address=excluded.address,
  order_count=excluded.order_count, lifetime_value=excluded.lifetime_value,
  last_order_at=excluded.last_order_at, updated_at=now();

create or replace function public.admin_create_gift_cards(
  p_count integer, p_discount integer, p_expires_at date, p_customer_id bigint default null
) returns table(code text)
language plpgsql security definer set search_path = public
as $$
declare i integer; v_code text;
begin
  if coalesce(auth.jwt()->>'email','') <> 'tuktak24.1@gmail.com' then
    raise exception 'Not authorized';
  end if;
  if p_count < 1 or p_count > 100 or p_discount < 1 or p_discount > 100 or p_expires_at < current_date then
    raise exception 'Invalid gift card settings';
  end if;
  for i in 1..p_count loop
    loop
      v_code := 'TT24-' || upper(substr(md5(random()::text || clock_timestamp()::text),1,8));
      exit when not exists(select 1 from public.gift_cards g where g.code=v_code);
    end loop;
    insert into public.gift_cards(code,discount_percent,expires_at,customer_id)
    values(v_code,p_discount,p_expires_at,p_customer_id);
    code := v_code;
    return next;
  end loop;
end $$;

create or replace function public.verify_gift_card(p_code text)
returns table(valid boolean, discount_percent integer, status text, expires_at date)
language sql security definer set search_path = public
as $$
  select (g.status='unused' and g.expires_at >= current_date),
         g.discount_percent,
         case when g.status='unused' and g.expires_at < current_date then 'expired' else g.status end,
         g.expires_at
  from public.gift_cards g where upper(g.code)=upper(trim(p_code)) limit 1;
$$;

create or replace function public.admin_redeem_gift_card(p_code text, p_order_code text, p_phone text)
returns boolean language plpgsql security definer set search_path = public
as $$
declare n integer;
begin
  if coalesce(auth.jwt()->>'email','') <> 'tuktak24.1@gmail.com' then
    raise exception 'Not authorized';
  end if;
  update public.gift_cards set status='used', redeemed_at=now(),
    order_code=p_order_code, redeemed_by_phone=p_phone
  where code=upper(trim(p_code)) and status='unused' and expires_at>=current_date;
  get diagnostics n = row_count;
  return n=1;
end $$;

grant execute on function public.verify_gift_card(text) to anon, authenticated;
grant execute on function public.admin_create_gift_cards(integer,integer,date,bigint) to authenticated;
grant execute on function public.admin_redeem_gift_card(text,text,text) to authenticated;
